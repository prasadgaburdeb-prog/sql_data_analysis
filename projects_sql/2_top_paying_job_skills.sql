/*
This SQL query retrieves the top 10 highest paying job postings for the position of "Data Analyst" that are available in any location. It selects relevant job details such as job ID, title, location, schedule type, average yearly salary, posting date, and the associated company name. The results are filtered to include only those postings with a non-null average yearly salary and are ordered in descending order based on the salary.question: Mhat skills are required for the top-paying data analyst jobs?
- Use the top 10 highest-paying Data Analyst jobs from first query
- Add the specific skills required for these roles
Why? It provides a detailed look at which high-paying jobs demand certain skills 
helping job seekers understand which skills to develop that align with top salaries
*/

with top_paying_jobs as (
    select job_id,
        job_title,
        salary_year_avg,
        name as company_name
    from
        job_postings_fact
    left join
        company_dim 
    on
        job_postings_fact.company_id = company_dim.company_id
    where
        job_title ilike 'Data analyst' and 
        job_location = 'Anywhere' and 
        salary_year_avg is not null
    order by
        salary_year_avg desc
    limit 10
)
select top_paying_jobs.*,
       skills
from top_paying_jobs
inner join skills_job_dim
on top_paying_jobs.job_id = skills_job_dim.job_id
inner join skills_dim
on skills_job_dim.skill_id = skills_dim.skill_id
order by 
salary_year_avg desc;

